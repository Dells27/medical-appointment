namespace PatientService.Domain.Entities
{
    public class MedicalDocument
    {
        public const long MaxFileSizeBytes = 10 * 1024 * 1024; // 10 MB

        public static readonly IReadOnlySet<string> AllowedContentTypes = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
        {
            "application/pdf", "image/jpeg", "image/png"
        };

        // What a patient can share with their doctors
        public static readonly IReadOnlySet<string> PatientDocumentTypes = new HashSet<string>
        {
            "LabResult", "Imaging", "PreviousExam", "ExternalPrescription", "ExternalReport", "Other"
        };

        // What a doctor can issue for a patient
        public static readonly IReadOnlySet<string> DoctorDocumentTypes = new HashSet<string>
        {
            "Prescription", "LabOrder", "ImagingOrder", "DiagnosisReport", "MedicalInstructions", "MedicalCertificate"
        };

        public Guid id { get; private set; }
        public Guid patientId { get; private set; }
        public string fileName { get; private set; } = null!;
        public string fileKey { get; private set; } = null!;   // S3 key
        public string fileType { get; private set; } = null!;  // MIME type
        public long fileSize { get; private set; }             // bytes
        public string documentType { get; private set; } = null!;
        public string uploadedByRole { get; private set; } = "Patient"; // "Patient" | "Doctor"
        public Guid? uploadedByUserId { get; private set; }
        public string? uploadedByName { get; private set; }
        public Guid? appointmentId { get; private set; }
        public string? description { get; private set; }
        public DateTime uploadedAt { get; private set; }

        private MedicalDocument() { }

        // The id is generated by EF when the document is added through the patient's collection.
        // Setting it here would make EF treat the new document as an existing row.
        public static MedicalDocument Create(Guid PatientId, string FileName, string FileKey, string FileType, long FileSize,
            string DocumentType, string UploadedByRole, Guid? UploadedByUserId, string? UploadedByName,
            Guid? AppointmentId, string? Description)
        {
            return new MedicalDocument()
            {
                patientId = PatientId,
                fileName = FileName,
                fileKey = FileKey,
                fileType = FileType,
                fileSize = FileSize,
                documentType = DocumentType,
                uploadedByRole = UploadedByRole,
                uploadedByUserId = UploadedByUserId,
                uploadedByName = UploadedByName,
                appointmentId = AppointmentId,
                description = string.IsNullOrWhiteSpace(Description) ? null : Description.Trim(),
                uploadedAt = DateTime.UtcNow
            };
        }

        // Validates the file before it is sent to S3
        public static void Validate(string role, string documentType, string contentType, long size)
        {
            var allowedTypes = role == "Doctor" ? DoctorDocumentTypes : PatientDocumentTypes;
            if (!allowedTypes.Contains(documentType))
                throw new ArgumentException($"Invalid document type. Allowed: {string.Join(", ", allowedTypes)}");

            if (!AllowedContentTypes.Contains(contentType))
                throw new ArgumentException("Only PDF, JPG and PNG files are allowed");

            if (size <= 0)
                throw new ArgumentException("The file is empty");

            if (size > MaxFileSizeBytes)
                throw new ArgumentException("The file is larger than 10 MB");
        }
    }
}
