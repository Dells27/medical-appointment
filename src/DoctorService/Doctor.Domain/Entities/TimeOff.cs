namespace DoctorService.Domain.Entities;

public enum TimeOffType
{
    Vacation,     // several full days
    DayOff,       // one or more full days
    BlockedHours  // a time range within a single day
}

// A period when the doctor does not take appointments
public class TimeOff
{
    public Guid Id { get; private set; }
    public Guid DoctorId { get; private set; }
    public TimeOffType Type { get; private set; }
    public DateOnly StartDate { get; private set; }
    public DateOnly EndDate { get; private set; }
    public TimeOnly? StartTime { get; private set; }  // only for BlockedHours
    public TimeOnly? EndTime { get; private set; }    // only for BlockedHours
    public string? Reason { get; private set; }
    public DateTime CreatedAt { get; private set; }

    private TimeOff() { }

    // Id is generated by EF when added through the doctor's collection (see AvailabilitySchedule)
    public static TimeOff Create(Guid doctorId, TimeOffType type, DateOnly startDate, DateOnly endDate,
        TimeOnly? startTime, TimeOnly? endTime, string? reason)
    {
        if (endDate < startDate)
            throw new ArgumentException("End date must be on or after the start date");

        if (type == TimeOffType.BlockedHours)
        {
            if (startTime is null || endTime is null)
                throw new ArgumentException("Blocked hours need a start and end time");
            if (startTime >= endTime)
                throw new ArgumentException("Start time must be earlier than end time");
            if (startDate != endDate)
                throw new ArgumentException("Blocked hours must be within a single day");
        }
        else
        {
            // Full days: times are ignored
            startTime = null;
            endTime = null;
        }

        return new TimeOff
        {
            DoctorId = doctorId,
            Type = type,
            StartDate = startDate,
            EndDate = endDate,
            StartTime = startTime,
            EndTime = endTime,
            Reason = string.IsNullOrWhiteSpace(reason) ? null : reason.Trim(),
            CreatedAt = DateTime.UtcNow
        };
    }

    public bool Covers(DateOnly date) => date >= StartDate && date <= EndDate;

    public bool IsFullDay => StartTime is null || EndTime is null;
}
